//! `.ferrule/ferrule.lock`: the version and the hash of every generated
//! file and block, which tells an untouched file from an edited one.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use serde::Deserialize;

use super::{Error, LOCK, VERSION};

/// FNV-1a over the bytes: stable across versions and platforms.
pub(crate) fn hash(text: &str) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in text.bytes() {
        h ^= u64::from(b);
        h = h.wrapping_mul(0x0100_0000_01b3);
    }
    format!("{h:016x}")
}

#[derive(Debug, Default, Deserialize)]
#[serde(default)]
pub(super) struct Lock {
    pub(super) version: String,
    /// `ferrule setup install` added the `@AGENTS.md` line to `CLAUDE.md`.
    pub(super) claude_md: bool,
    /// The `permissions.deny` rules ferrule added to the settings.
    pub(super) deny: Vec<String>,
    /// Generated path (or `<file>#ferrule` for a block) → hash.
    pub(super) files: BTreeMap<String, String>,
}

impl Lock {
    pub(super) fn load(root: &Path) -> Result<Lock, Error> {
        match std::fs::read_to_string(root.join(LOCK)) {
            Ok(t) => toml::from_str(&t).map_err(|e| Error::Lock(e.to_string())),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Lock::default()),
            Err(e) => Err(e.into()),
        }
    }

    pub(super) fn text(&self) -> String {
        let mut out = format!(
            "# generated by ferrule {VERSION}, never edit\nversion = {}\n",
            quote(&self.version)
        );
        let _ = writeln!(out, "claude_md = {}", self.claude_md);
        let deny: Vec<String> = self.deny.iter().map(|d| quote(d)).collect();
        let _ = writeln!(out, "deny = [{}]", deny.join(", "));
        out.push_str("\n[files]\n");
        for (k, v) in &self.files {
            let _ = writeln!(out, "{} = {}", quote(k), quote(v));
        }
        out
    }
}

pub(super) fn quote(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}
