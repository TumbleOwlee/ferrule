/// One thing install keeps in the project.
#[derive(Debug, Clone)]
pub(super) enum Item {
    /// A whole file ferrule owns.
    File {
        path: String,
        text: String,
        exec: bool,
    },
    /// A marked block inside a project file; the file is created when
    /// missing.
    Block {
        path: String,
        begin: &'static str,
        end: &'static str,
        body: String,
    },
}

impl Item {
    pub(super) fn key(&self) -> String {
        match self {
            Item::File { path, .. } => path.clone(),
            Item::Block { path, .. } => format!("{path}#ferrule"),
        }
    }

    pub(super) fn path(&self) -> &str {
        match self {
            Item::File { path, .. } | Item::Block { path, .. } => path,
        }
    }

    /// What the lock hashes: the file, or the block with its markers.
    pub(super) fn expected(&self) -> String {
        match self {
            Item::File { text, .. } => text.clone(),
            Item::Block {
                begin, end, body, ..
            } => format!("{begin}\n{body}{end}\n"),
        }
    }

    pub(super) fn current(&self, root: &Path) -> Option<String> {
        let text = std::fs::read_to_string(root.join(self.path())).ok()?;
        match self {
            Item::File { .. } => Some(text),
            Item::Block { begin, end, .. } => {
                block(&text, begin, end).map(|(s, e)| text[s..e].to_owned())
            }
        }
    }

    /// The file's whole new text.
    pub(super) fn render(&self, root: &Path) -> String {
        match self {
            Item::File { text, .. } => text.clone(),
            Item::Block { begin, end, .. } => {
                let old = std::fs::read_to_string(root.join(self.path())).unwrap_or_default();
                let new = self.expected();
                match block(&old, begin, end) {
                    Some((s, e)) => format!("{}{new}{}", &old[..s], &old[e..]),
                    None if old.is_empty() => new,
                    None => format!(
                        "{}{}\n{new}",
                        old,
                        if old.ends_with('\n') { "" } else { "\n" }
                    ),
                }
            }
        }
    }
}

fn versioned(t: &str) -> String {
    t.replace("{version}", VERSION)
}

/// An installed agent or skill template: includes spliced, version filled.
fn template(text: &str) -> String {
    versioned(&crate::guide::expand(text))
}

/// The project's lefthook configuration file, if it has one.
pub(super) fn lefthook(root: &Path) -> Option<&'static str> {
    LEFTHOOK_FILES
        .iter()
        .copied()
        .find(|f| root.join(f).is_file())
}

const LEFTHOOK_YML: &str = "# generated by ferrule {version}, edit .ferrule/ instead
pre-commit:
  commands:
    ferrule-main-branch:
      run: .ferrule/ferrule hook git pre-commit
commit-msg:
  commands:
    ferrule-trailers:
      run: .ferrule/ferrule hook git commit-msg {1}
pre-push:
  commands:
    ferrule-main-branch:
      run: .ferrule/ferrule hook git pre-push {1} {2}
      use_stdin: true
";

/// Every file and block install keeps, for the project as it stands.
pub(super) fn items(root: &Path) -> Vec<Item> {
    let mut out = vec![
        Item::File {
            path: ".ferrule/ferrule".into(),
            text: versioned(SHIM),
            exec: true,
        },
        Item::File {
            path: ".ferrule/.gitignore".into(),
            text: versioned(GITIGNORE),
            exec: false,
        },
    ];
    for (name, text) in AGENTS {
        out.push(Item::File {
            path: format!(".claude/agents/fe-{name}.md"),
            text: template(text),
            exec: false,
        });
    }
    for (name, text) in SKILLS {
        out.push(Item::File {
            path: format!(".claude/skills/fe-{name}/SKILL.md"),
            text: template(text),
            exec: false,
        });
    }
    out.push(Item::Block {
        path: "AGENTS.md".into(),
        begin: "<!-- ferrule:begin -->",
        end: "<!-- ferrule:end -->",
        body: AGENTS_BLOCK.to_owned(),
    });
    if let Some(file) = lefthook(root)
        && !foreign_extends(root, file)
    {
        out.push(Item::File {
            path: ".ferrule/lefthook.yml".into(),
            text: versioned(LEFTHOOK_YML),
            exec: false,
        });
        out.push(Item::Block {
            path: file.to_owned(),
            begin: "# ferrule:begin",
            end: "# ferrule:end",
            body: "extends:\n  - .ferrule/lefthook.yml\n".to_owned(),
        });
    }
    out
}

/// A top-level `extends:` outside ferrule's block: lefthook takes one
/// list, so the user adds `.ferrule/lefthook.yml` to it.
pub(super) fn foreign_extends(root: &Path, file: &str) -> bool {
    let text = std::fs::read_to_string(root.join(file)).unwrap_or_default();
    let outside = match block(&text, "# ferrule:begin", "# ferrule:end") {
        Some((s, e)) => format!("{}{}", &text[..s], &text[e..]),
        None => text,
    };
    outside.lines().any(|l| l.starts_with("extends:"))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::guide::{Fragment, VARS};

    fn claude_files() -> Vec<(String, String)> {
        let dir = tempfile::tempdir().unwrap();
        items(dir.path())
            .into_iter()
            .filter_map(|i| match i {
                Item::File { path, text, .. } if path.starts_with(".claude/") => Some((path, text)),
                _ => None,
            })
            .collect()
    }

    /// GA-R-058 — an installed agent file holds its role fragment's text,
    /// spliced from an include line its source holds.
    #[test]
    fn ut_templates_splice_their_role_fragment() {
        let files = claude_files();
        let pairs = [
            ("author", Fragment::AuthorRole),
            ("architect", Fragment::ArchitectRole),
            ("planner", Fragment::PlannerRole),
            ("implementer", Fragment::ImplementerRole),
        ];
        for (agent, f) in pairs {
            let path = format!(".claude/agents/fe-{agent}.md");
            let (_, text) = files.iter().find(|(p, _)| *p == path).unwrap();
            assert!(text.contains(f.text().trim_end()), "{agent}");
            let raw = AGENTS.iter().find(|(n, _)| *n == agent).unwrap().1;
            assert!(!raw.contains(f.text().trim_end()), "{agent} raw");
            assert!(raw.contains(&format!("<!-- include: {agent}-role -->")));
        }
    }

    /// GA-E-004 — no installed file keeps an include line, a run
    /// placeholder or a lane or done tag.
    #[test]
    fn ut_installed_templates_take_no_placeholders_or_tags() {
        let files = claude_files();
        assert!(files.len() >= 9);
        for (path, text) in files {
            assert!(!text.contains("<!-- include:"), "{path}");
            for v in VARS {
                assert!(!text.contains(&format!("{{{v}}}")), "{path}: {v}");
            }
            for l in text.lines() {
                let l = l.trim_start();
                assert!(
                    !l.starts_with("<!-- lane:") && !l.starts_with("<!-- done:"),
                    "{path}"
                );
            }
        }
    }
}
