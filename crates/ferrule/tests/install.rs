//! `ferrule install`, `install --check` and `uninstall` on scratch
//! repositories.

mod golden;

use std::path::Path;
use std::process::Command;

use golden::Run;

fn git(dir: &Path, args: &[&str]) {
    let ok = Command::new("git")
        .args(args)
        .current_dir(dir)
        .output()
        .unwrap()
        .status
        .success();
    assert!(ok, "git {args:?}");
}

fn ferrule(root: &Path, args: &[&str]) -> String {
    Run::new(args)
        .env("CLAUDE_PROJECT_DIR", root)
        .cwd(root)
        .text()
}

fn read(root: &Path, path: &str) -> String {
    std::fs::read_to_string(root.join(path)).unwrap_or_else(|e| panic!("{path}: {e}"))
}

/// A git repository with a Cargo.toml.
fn repo() -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    git(dir.path(), &["init", "-q", "-b", "main"]);
    std::fs::write(dir.path().join("Cargo.toml"), "[package]\nname = \"x\"\n").unwrap();
    dir
}

const VERSION: &str = env!("CARGO_PKG_VERSION");

#[test]
fn it_install_writes_the_adapters_and_is_idempotent() {
    let dir = repo();
    let root = dir.path();
    let out = ferrule(root, &["install"]);
    let first = out.lines().next().unwrap();
    assert!(
        first.starts_with(&format!(
            "install=done version={VERSION} host=claude stack=rust viewer="
        )),
        "{out}"
    );
    assert!(first.contains(" hooks=git written="), "{out}");
    assert!(out.ends_with("exit=0"), "{out}");

    let config = read(root, ".ferrule/ferrule.toml");
    assert!(
        config.starts_with(&format!("version = \"{VERSION}\"\n")),
        "{config}"
    );
    assert!(
        config.contains("cmd = [\"cargo\", \"fmt\", \"--check\"]"),
        "{config}"
    );
    let shim = read(root, ".ferrule/ferrule");
    assert!(
        shim.contains(&format!("--tag v{VERSION} --locked")),
        "{shim}"
    );
    let agent = read(root, ".claude/agents/fe-implementer.md");
    assert!(agent.starts_with("---\nname: fe-implementer\n"), "{agent}");
    assert!(
        agent.contains(&format!("generated by ferrule {VERSION}")),
        "{agent}"
    );
    assert!(
        agent.contains("`ferrule guide implementer --stage s<n>`"),
        "{agent}"
    );
    assert!(
        read(root, ".claude/agents/fe-reviewer.md").contains("/.ferrule/ferrule hook reviewer")
    );
    assert!(
        read(root, ".claude/skills/fe-feature/SKILL.md").starts_with("---\nname: fe-feature\n")
    );
    let agents = read(root, "AGENTS.md");
    assert!(
        agents.starts_with("<!-- ferrule:begin -->\n## Workflow — ferrule\n"),
        "{agents}"
    );
    assert!(agents.ends_with("<!-- ferrule:end -->\n"), "{agents}");
    assert_eq!(read(root, "CLAUDE.md"), "@AGENTS.md\n");
    assert!(read(root, "docs/specs/README.md").contains("## Rules for writing specs"));
    assert!(read(root, ".git/hooks/commit-msg").contains("hook git commit-msg \"$@\""));

    let settings: serde_json::Value =
        serde_json::from_str(&read(root, ".claude/settings.json")).unwrap();
    assert_eq!(
        settings["hooks"]["PreToolUse"][0]["hooks"][0]["command"],
        "\"$CLAUDE_PROJECT_DIR\"/.ferrule/ferrule hook shell"
    );
    let deny = settings["permissions"]["deny"].as_array().unwrap();
    assert!(deny.iter().any(|r| r == "Bash(git push:*)"));
    assert!(deny.iter().any(|r| r == "Edit(**/.ferrule/state.db)"));

    assert_eq!(
        ferrule(root, &["install", "--check"]),
        format!("install-check=ok version={VERSION}\nexit=0")
    );
    let again = ferrule(root, &["install"]);
    assert!(
        again.lines().next().unwrap().ends_with(" written=0 kept=0"),
        "{again}"
    );
    assert_eq!(read(root, "AGENTS.md").matches("ferrule:begin").count(), 1);
    assert_eq!(read(root, "CLAUDE.md"), "@AGENTS.md\n");
}

#[test]
fn it_install_merges_into_existing_project_files() {
    let dir = repo();
    let root = dir.path();
    std::fs::create_dir_all(root.join(".claude")).unwrap();
    std::fs::write(
        root.join(".claude/settings.json"),
        r#"{"model": "opus", "hooks": {"PreToolUse": [{"matcher": "Edit", "hooks": [{"type": "command", "command": "mine"}]}]}, "permissions": {"deny": ["Bash(rm -rf:*)"]}}"#,
    )
    .unwrap();
    std::fs::write(root.join("AGENTS.md"), "# Agents\n\nOur rules.\n").unwrap();
    std::fs::write(root.join("CLAUDE.md"), "# Claude\n").unwrap();
    std::fs::write(
        root.join(".lefthook.yml"),
        "pre-commit:\n  commands:\n    fmt:\n      run: cargo fmt --check\n",
    )
    .unwrap();
    let out = ferrule(root, &["install"]);
    assert!(out.contains(" hooks=lefthook "), "{out}");
    assert!(out.contains("hint=run lefthook install"), "{out}");

    let text = read(root, ".claude/settings.json");
    assert!(
        text.starts_with("{\n  \"model\": \"opus\",\n  \"hooks\": {"),
        "key order kept: {text}"
    );
    let s: serde_json::Value = serde_json::from_str(&text).unwrap();
    assert_eq!(s["hooks"]["PreToolUse"][0]["hooks"][0]["command"], "mine");
    assert_eq!(s["hooks"]["PreToolUse"].as_array().unwrap().len(), 2);
    assert_eq!(s["permissions"]["deny"][0], "Bash(rm -rf:*)");
    assert!(
        read(root, "AGENTS.md").starts_with("# Agents\n\nOur rules.\n\n<!-- ferrule:begin -->\n")
    );
    assert_eq!(read(root, "CLAUDE.md"), "# Claude\n\n@AGENTS.md\n");
    assert!(
        read(root, ".lefthook.yml")
            .ends_with("# ferrule:begin\nextends:\n  - .ferrule/lefthook.yml\n# ferrule:end\n")
    );
    assert!(
        read(root, ".ferrule/lefthook.yml")
            .contains("run: .ferrule/ferrule hook git commit-msg {1}")
    );
    assert!(!root.join(".git/hooks/commit-msg").exists());

    // A guard allow-list re-opens commands in the deny rules too.
    let config = read(root, ".ferrule/ferrule.toml") + "\n[guard]\nallow = [\"gh issue\"]\n";
    std::fs::write(root.join(".ferrule/ferrule.toml"), config).unwrap();
    let check = ferrule(root, &["install", "--check"]);
    assert!(
        check.contains("drift path=.claude/settings.json reason=edited"),
        "{check}"
    );
    ferrule(root, &["install"]);
    let s: serde_json::Value = serde_json::from_str(&read(root, ".claude/settings.json")).unwrap();
    let deny = s["permissions"]["deny"].as_array().unwrap();
    assert!(
        !deny
            .iter()
            .any(|r| r.as_str().unwrap().starts_with("Bash(gh issue"))
    );
    assert!(deny.iter().any(|r| r == "Bash(rm -rf:*)"));
    assert!(ferrule(root, &["install", "--check"]).ends_with("exit=0"));
}

#[test]
fn it_install_keeps_edited_files_and_refuses_foreign_ones() {
    let dir = repo();
    let root = dir.path();
    std::fs::create_dir_all(root.join(".claude/agents")).unwrap();
    std::fs::write(root.join(".claude/agents/fe-author.md"), "mine\n").unwrap();
    assert_eq!(
        ferrule(root, &["install"]),
        "install=refused reason=foreign path=.claude/agents/fe-author.md hint=--force overwrites it\nexit=1"
    );
    assert!(
        !root.join(".ferrule").exists(),
        "nothing written before the refusal"
    );
    assert!(ferrule(root, &["install", "--force"]).ends_with("exit=0"));

    let planner = root.join(".claude/agents/fe-planner.md");
    let edited = std::fs::read_to_string(&planner).unwrap() + "One more rule.\n";
    std::fs::write(&planner, &edited).unwrap();
    let check = ferrule(root, &["install", "--check"]);
    assert!(
        check.starts_with(
            "install-check=drift count=1\ndrift path=.claude/agents/fe-planner.md reason=edited\n"
        ),
        "{check}"
    );
    let out = ferrule(root, &["install"]);
    assert!(
        out.contains("kept=.claude/agents/fe-planner.md new=.claude/agents/fe-planner.md.ferrule-new diff=+0/-1"),
        "{out}"
    );
    assert_eq!(std::fs::read_to_string(&planner).unwrap(), edited);
}

#[test]
fn it_a_pinned_version_refuses_other_binaries() {
    let dir = repo();
    let root = dir.path();
    ferrule(root, &["install"]);
    let config = read(root, ".ferrule/ferrule.toml")
        .replace(&format!("version = \"{VERSION}\""), "version = \"0.0.1\"");
    std::fs::write(root.join(".ferrule/ferrule.toml"), config).unwrap();
    assert_eq!(ferrule(root, &["card", "board"]), "exit=1");
    let check = ferrule(root, &["install", "--check"]);
    assert!(
        check.contains(&format!(
            "drift path=.ferrule/ferrule.toml reason=version pinned=0.0.1 binary={VERSION}"
        )),
        "{check}"
    );
    assert!(ferrule(root, &["install"]).ends_with("exit=0"));
    assert!(ferrule(root, &["card", "board"]).ends_with("exit=0"));
}

#[test]
fn it_uninstall_takes_out_what_install_put_in() {
    let dir = repo();
    let root = dir.path();
    std::fs::write(root.join("AGENTS.md"), "# Agents\n").unwrap();
    ferrule(root, &["install"]);
    ferrule(root, &["card", "new", "demo"]);
    let edited = read(root, ".claude/skills/fe-review/SKILL.md") + "x\n";
    std::fs::write(root.join(".claude/skills/fe-review/SKILL.md"), edited).unwrap();

    let out = ferrule(root, &["uninstall"]);
    assert!(out.starts_with("uninstall=done removed="), "{out}");
    assert!(
        out.contains("kept=.claude/skills/fe-review/SKILL.md reason=edited"),
        "{out}"
    );
    assert!(!root.join(".claude/agents/fe-author.md").exists());
    assert!(!root.join(".claude/skills/fe-feature").exists());
    assert_eq!(read(root, "AGENTS.md"), "# Agents\n\n");
    assert!(!root.join("CLAUDE.md").exists());
    assert!(!root.join(".git/hooks/pre-push").exists());
    assert!(
        !root.join(".claude/settings.json").exists()
            || !read(root, ".claude/settings.json").contains("ferrule")
    );
    assert!(root.join(".ferrule/state.db").exists(), "the board stays");

    assert!(ferrule(root, &["uninstall", "--purge"]).ends_with("exit=0"));
    assert!(!root.join(".ferrule").exists());
}

#[test]
fn it_install_writes_into_the_worktree_it_runs_in() {
    let dir = repo();
    let root = dir.path();
    git(
        root,
        &[
            "-c",
            "user.name=t",
            "-c",
            "user.email=t@t",
            "-c",
            "commit.gpgsign=false",
            "add",
            ".",
        ],
    );
    git(
        root,
        &[
            "-c",
            "user.name=t",
            "-c",
            "user.email=t@t",
            "-c",
            "commit.gpgsign=false",
            "commit",
            "-qm",
            "x",
        ],
    );
    let wt = root.join("wt");
    git(
        root,
        &[
            "worktree",
            "add",
            "-q",
            wt.to_str().unwrap(),
            "-b",
            "feat/x",
        ],
    );
    let out = ferrule(&wt, &["install"]);
    assert!(out.ends_with("exit=0"), "{out}");
    assert!(wt.join(".claude/agents/fe-author.md").is_file());
    assert!(
        !root.join(".claude").exists(),
        "the main checkout stays untouched"
    );
    assert!(
        !root.join(".ferrule").exists(),
        "the main checkout stays untouched"
    );
}
